"""Seed coreo/posturas/base.toml with postures taken from the gesture clips.

Every posture here is a frame of a clip the robot already performs (and a policy
already tracks), so the library starts from poses known to be reachable and
balanced rather than from guesses. Claw postures are written for the LEFT claw
(`J0..J4`); coreo mirrors them for the right. `tenazas.*` name both arms' joints
in full, for poses that are not symmetric. Leg stances name all 12 leg joints.

    python extraer_posturas.py <jumper checkout> <out.toml>
"""

import sys
from pathlib import Path

import numpy as np

OLD = {0: "LF", 1: "LM", 2: "LR", 3: "RR", 4: "RM", 5: "RF"}
LEGS = ("LM", "RM", "LR", "RR")


def frames(repo: Path, gesture: str) -> dict[str, np.ndarray]:
    z = np.load(repo / "tasks" / "jumper" / f"gesture_{gesture}" / "media" / f"{gesture}.npz")
    q = {}
    for k in z.files:
        if k.startswith("L") and "_j" in k:
            q[f"{OLD[int(k[1])]}_J{k[-1]}_joint"] = np.asarray(z[k], dtype=np.float64)
    return q


def claw(q, i, side="LF"):
    return {f"J{j}": q[f"{side}_J{j}_joint"][i] for j in range(5)}


def legs(q, i):
    return {f"{leg}_J{j}_joint": q[f"{leg}_J{j}_joint"][i] for leg in LEGS for j in range(3)}


def both_claws(q, i):
    return {f"{side}_J{j}_joint": q[f"{side}_J{j}_joint"][i] for side in ("LF", "RF") for j in range(5)}


def mirror_claw(c):
    # RF -> LF: every joint flips except J1 (symmetry.py, _SIGN_KEEP).
    return {k: (v if k == "J1" else -v) for k, v in c.items()}


def table(name, values, note):
    body = "\n".join(f"{k} = {v:.4f}" for k, v in values.items())
    return f"# {note}\n[{name}]\n{body}\n"


def main(repo: Path, dest: Path) -> None:
    out = ["# Generated by puente/extraer_posturas.py from the gesture clips; edit freely,\n"
           "# but a new posture should be checked with `coreo verificar` before training.\n"]

    h = frames(repo, "hello")
    j1 = h["LF_J1_joint"]
    up = int(np.argmin(j1))
    # The wave: the largest local maximum of LF_J1 while the arm is up (J1 < -2.0).
    up_rows = np.nonzero(j1 < -2.0)[0]
    seg = j1[up_rows[0]:up_rows[-1]]
    peaks = [i for i in range(1, len(seg) - 1) if seg[i] >= seg[i - 1] and seg[i] > seg[i + 1]]
    wave = up_rows[0] + max(peaks, key=lambda i: seg[i]) if peaks else up
    out.append(table("tenaza.arriba", claw(h, up), "hello: arm at its highest"))
    out.append(table("tenaza.arriba_b", claw(h, wave), "hello: the other end of the wave"))
    out.append(table("patas.apoyo_atras", legs(h, up), "hello: the four legs leaning back under a raised arm"))
    from tasks.jumper.common.constants import HOME

    home = {k: np.array([v]) for k, v in HOME.items()}
    out.append(table("tenaza.reposo", claw(home, 0), "HOME, from constants.py"))
    out.append(table("patas.de_pie", legs(home, 0), "HOME, from constants.py"))

    b = frames(repo, "bow")
    mid = len(b["LF_J1_joint"]) // 2
    # Both arms as the clip has them: the bow is not symmetric (RF_J3 is 0.35 rad
    # off LF's mirror), and the mirrored pair pitched the base 51 degrees.
    out.append(table("tenazas.reverencia", both_claws(b, mid), "bow: middle of the bow, both arms"))
    out.append(table("patas.reverencia", legs(b, mid), "bow: middle of the bow"))

    p = frames(repo, "paw")
    mid = len(p["LF_J1_joint"]) // 2
    out.append(table("tenaza.ofrecer", claw(p, mid), "paw: claw held out forward"))
    out.append(table("patas.sentado", legs(p, mid), "paw: sitting back on the rear legs"))

    s = frames(repo, "salute")
    mid = len(s["RF_J1_joint"]) // 2
    out.append(table("tenaza.saludo_militar", mirror_claw(claw(s, mid, "RF")),
                     "salute: right claw at the brow, mirrored to the left"))
    out.append(table("patas.alto", legs(s, mid), "salute: standing tall"))

    dest.write_text("\n".join(out))
    print(f"wrote {dest}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
